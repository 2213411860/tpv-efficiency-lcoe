const assert=require('node:assert/strict');
const fs=require('node:fs');
const M=require('./model.js');
const D=JSON.parse(fs.readFileSync('./data/dataset.json','utf8'));
const settings={lcoh:1,cf:1,cpa:D.default_cpa};
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-11*Math.max(1,Math.abs(b)),`${a} != ${b}`);
assert.equal(D.records.length,20);
for(const row of D.records){
  const c=M.cost(row,settings);close(c.lcoe_dollar_kwh,row.reference_lcoe_dollar_kwh);
  close(c.lcoe_dollar_kwh,c.lcoe_cell_dollar_kwh+c.lcoe_heat_dollar_kwh);
  close(c.p_abs_W_cm2,c.p_out_W_cm2/(c.eta_pair_pct/100));
  const hot=M.cost(row,{...settings,lcoh:10});close(hot.lcoe_heat_dollar_kwh,c.lcoe_heat_dollar_kwh*10);
  const lowCF=M.cost(row,{...settings,cf:.5});close(lowCF.lcoe_cell_dollar_kwh,c.lcoe_cell_dollar_kwh*2);
  const free=M.cost(row,{lcoh:0,cf:1,cpa:{...D.default_cpa,[row.cell_type]:0}});close(free.lcoe_dollar_kwh,0);
}
const custom={cpa:7,power:2,heat:8};
close(M.cost(M.customRow(custom),settings).CPA_dollar_cm2,7);
close(M.customRow(custom).eta_pair_pct,25);
close(M.cost(M.customRow({...custom,heat:16}),settings).lcoe_heat_dollar_kwh,.08);
assert.equal(M.customRow(custom).cell_type,'Custom');
assert.equal(M.customRow(custom).emitter_temperature_K,null);
assert.throws(()=>M.customRow({...custom,heat:1}),RangeError);
assert.throws(()=>M.customRow({...custom,power:0}),RangeError);
assert.throws(()=>M.customRow({...custom,heat:0}),RangeError);
assert.throws(()=>M.cost(D.records[0],{...settings,cf:0}),RangeError);
assert.throws(()=>M.cost(D.records[0],{...settings,lcoh:NaN}),RangeError);
const visible=[...D.records.map(row=>M.cost(row,settings)),M.cost(M.customRow(custom),settings)];
const scale=M.bubbleScale(visible,D.bubble_scale);
close(scale.min_lcoe_dollar_kwh,Math.min(...visible.map(r=>r.lcoe_dollar_kwh)));
close(scale.max_lcoe_dollar_kwh,Math.max(...visible.map(r=>r.lcoe_dollar_kwh)));
close(M.bubbleArea(0,scale),2500);
close(M.bubbleArea(scale.min_lcoe_dollar_kwh,scale),2500);
close(M.bubbleArea(scale.max_lcoe_dollar_kwh,scale),16);
close(M.bubbleArea(Math.sqrt(scale.min_lcoe_dollar_kwh*scale.max_lcoe_dollar_kwh),scale),729);
const known=M.bubbleScale([.1,1,10].map(n=>({lcoe_dollar_kwh:n})),D.bubble_scale);
close(M.bubbleArea(1,known),729);
const mixed=M.bubbleScale([0,1,9].map(n=>({lcoe_dollar_kwh:n})),D.bubble_scale);
close(M.bubbleArea(0,mixed),2500);close(M.bubbleArea(9,mixed),16);
close(M.bubbleArea(Math.sqrt(10)-1,mixed),729);
assert.ok(M.bubbleArea(0,mixed)>M.bubbleArea(1,mixed));
const linearArea=v=>16+2484*(scale.max_lcoe_dollar_kwh-v)/(scale.max_lcoe_dollar_kwh-scale.min_lcoe_dollar_kwh);
assert.ok(Math.sqrt(M.bubbleArea(.1,scale)/M.bubbleArea(1,scale))>1.5*Math.sqrt(linearArea(.1)/linearArea(1)));
for(const value of [0,2]){
  const identical=M.bubbleScale([{lcoe_dollar_kwh:value},{lcoe_dollar_kwh:value}],D.bubble_scale);
  close(M.bubbleArea(value,identical),729);
}
assert.throws(()=>M.bubbleScale([],D.bubble_scale),RangeError);
assert.throws(()=>M.bubbleScale([{lcoe_dollar_kwh:Infinity}],D.bubble_scale),RangeError);
const costs=[0,.001,.01,.1,1,10,100];
for(let i=1;i<costs.length;i++)assert.ok(M.bubbleArea(costs[i],scale)<=M.bubbleArea(costs[i-1],scale));
assert.ok(M.csv([{...M.customRow(custom),work:'=HYPERLINK("bad")'}]).includes("'=HYPERLINK"));
const scan=fs.readFileSync('./data/lin_si_temperature_scan.csv','utf8').replace(/^\ufeff/,'').trim().split(/\r?\n/);
const names=scan[0].split(','),ti=names.indexOf('temperature_K'),ci=names.indexOf('selection_lcoe_dollar_kwh');
const simpleRows=scan.slice(1).map(line=>line.split(','));
const maxRow=simpleRows.reduce((a,b)=>Number(a[ci])>Number(b[ci])?a:b);
assert.equal(simpleRows.length,51);assert.equal(Number(maxRow[ti]),D.lin_selection.temperature_K);
close(Number(maxRow[ci]),D.lin_selection.selected_lcoe_dollar_kwh);
console.log('PASS: 20 baseline costs; capital/heat decomposition; heat, CF and zero-cost scenarios; custom CPA independence and Pout/Qabs efficiency; invalid input rejection; monotonic bubble scale; CSV escaping; maximum-LCOE selection over 51 temperatures.');
